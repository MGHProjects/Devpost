/**
 * Extracts the bind pose of the WebXR "generic-hand" models (public/models/
 * right.glb, left.glb) and IWER's relaxed-hand joint radii, and writes them to
 * src/core/hand-bind.ts as plain constant arrays (consumed by core/fk-hand.ts).
 *
 * The GLBs have a flat skeleton: all 25 joints are direct children of an
 * untransformed "Armature" node, so each node's TRS is already in model space.
 * The script also checks the skin's inverse bind matrices against the node
 * transforms and prints the largest mismatch.
 *
 * Usage: node scripts/gen-hand-bind.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { relaxedHandPose } from 'iwer/lib/device/configs/hand/relaxed.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const JOINTS = [
  'wrist',
  'thumb-metacarpal', 'thumb-phalanx-proximal', 'thumb-phalanx-distal', 'thumb-tip',
  'index-finger-metacarpal', 'index-finger-phalanx-proximal', 'index-finger-phalanx-intermediate',
  'index-finger-phalanx-distal', 'index-finger-tip',
  'middle-finger-metacarpal', 'middle-finger-phalanx-proximal', 'middle-finger-phalanx-intermediate',
  'middle-finger-phalanx-distal', 'middle-finger-tip',
  'ring-finger-metacarpal', 'ring-finger-phalanx-proximal', 'ring-finger-phalanx-intermediate',
  'ring-finger-phalanx-distal', 'ring-finger-tip',
  'pinky-finger-metacarpal', 'pinky-finger-phalanx-proximal', 'pinky-finger-phalanx-intermediate',
  'pinky-finger-phalanx-distal', 'pinky-finger-tip',
];

function readGlb(path) {
  const buf = readFileSync(path);
  if (buf.readUInt32LE(0) !== 0x46546c67) throw new Error(`${path}: not a GLB`);
  const jsonLen = buf.readUInt32LE(12);
  const json = JSON.parse(buf.subarray(20, 20 + jsonLen).toString('utf8'));
  const binStart = 20 + jsonLen + 8;
  const bin = buf.subarray(binStart, binStart + buf.readUInt32LE(20 + jsonLen));
  return { json, bin };
}

/** Column-major TRS matrix (scale ignored: it is 1 within float noise). */
function trsMatrix(t, q) {
  const [x, y, z, w] = q;
  return [
    1 - 2 * (y * y + z * z), 2 * (x * y + z * w), 2 * (x * z - y * w), 0,
    2 * (x * y - z * w), 1 - 2 * (x * x + z * z), 2 * (y * z + x * w), 0,
    2 * (x * z + y * w), 2 * (y * z - x * w), 1 - 2 * (x * x + y * y), 0,
    t[0], t[1], t[2], 1,
  ];
}

function mul(a, b) {
  const o = new Array(16).fill(0);
  for (let c = 0; c < 4; c++)
    for (let r = 0; r < 4; r++)
      for (let k = 0; k < 4; k++) o[c * 4 + r] += a[k * 4 + r] * b[c * 4 + k];
  return o;
}

function extract(path) {
  const { json, bin } = readGlb(path);
  const pos = [];
  const rot = [];
  for (const name of JOINTS) {
    const node = json.nodes.find((n) => n.name === name);
    if (!node) throw new Error(`${path}: joint ${name} missing`);
    const t = node.translation ?? [0, 0, 0];
    let q = node.rotation ?? [0, 0, 0, 1];
    const len = Math.hypot(...q);
    q = q.map((v) => v / len);
    if (q[3] < 0) q = q.map((v) => -v);
    pos.push(...t);
    rot.push(...q);
  }
  // Sanity: the armature is untransformed and IBM_j * bind_j == identity.
  const armature = json.nodes.find((n) => n.name === 'Armature');
  if (armature.translation || armature.rotation || armature.scale || armature.matrix)
    throw new Error(`${path}: Armature has a transform`);
  const skin = json.skins[0];
  const acc = json.accessors[skin.inverseBindMatrices];
  const view = json.bufferViews[acc.bufferView];
  const ibm = new Float32Array(bin.buffer, bin.byteOffset + (view.byteOffset ?? 0) + (acc.byteOffset ?? 0), acc.count * 16);
  let maxErr = 0;
  skin.joints.forEach((nodeIdx, s) => {
    const j = JOINTS.indexOf(json.nodes[nodeIdx].name);
    const m = mul(Array.from(ibm.subarray(s * 16, s * 16 + 16)), trsMatrix(pos.slice(j * 3, j * 3 + 3), rot.slice(j * 4, j * 4 + 4)));
    for (let i = 0; i < 16; i++) maxErr = Math.max(maxErr, Math.abs(m[i] - (i % 5 === 0 ? 1 : 0)));
  });
  console.log(`${path}: 25 joints, max |IBM * bind - I| = ${maxErr.toExponential(2)}`);
  return { pos, rot };
}

const fmt = (arr, per) => {
  const lines = [];
  for (let i = 0; i < arr.length; i += per) lines.push('  ' + arr.slice(i, i + per).map((v) => +v.toFixed(7)).join(', ') + ',');
  return lines.join('\n');
};

const right = extract(resolve(root, 'public/models/right.glb'));
const left = extract(resolve(root, 'public/models/left.glb'));
const radii = JOINTS.map((n) => relaxedHandPose.jointTransforms[n].radius);

const out = `/**
 * GENERATED by scripts/gen-hand-bind.mjs — do not edit by hand.
 *
 * Bind pose of the WebXR "generic-hand" models (public/models/{right,left}.glb,
 * MIT, webxr-input-profiles) in glTF model space: per joint (core/joints.ts
 * order) translation x,y,z and rotation quaternion x,y,z,w. Plus IWER's relaxed
 * hand joint radii (metres), used as the default FK joint radii.
 */

export const BIND_RIGHT_POS: readonly number[] = [
${fmt(right.pos, 3)}
];

export const BIND_RIGHT_ROT: readonly number[] = [
${fmt(right.rot, 4)}
];

export const BIND_LEFT_POS: readonly number[] = [
${fmt(left.pos, 3)}
];

export const BIND_LEFT_ROT: readonly number[] = [
${fmt(left.rot, 4)}
];

export const DEFAULT_RADII: readonly number[] = [
${fmt(radii, 5)}
];
`;
writeFileSync(resolve(root, 'src/core/hand-bind.ts'), out);
console.log('wrote src/core/hand-bind.ts');
